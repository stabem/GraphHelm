def _norm(p: str) -> str:
    return str(p).replace("\\", "/")


def is_artifact(path: str, arm: str) -> bool:
    return any(_norm(path).startswith(pref) for pref in ARTIFACT_PREFIXES[arm])


def filter_check(check: dict, arm: str) -> dict:
    """Remove OUTSIDE_CARD findings that point into the methodology artifact directories. An exit-2
    refusal whose only blocking findings were those becomes a pass-equivalent envelope."""
    if not check.get("data"):
        return check
    findings = check["data"].get("findings") or []
    kept = [f for f in findings
            if not (f.get("rule") == doless.OUTSIDE_CARD_RULE and is_artifact(f.get("path", ""), arm))]
    out = dict(check)
    out["data"] = {**check["data"], "findings": kept}
    if check.get("exit") == 2 and not any(f.get("blocking") for f in kept):
        out["exit"] = 0
    return out


def numstat_totals(wt: Path, base: str, head: str, arm: str) -> tuple[int, int]:
    total, code = 0, 0
    for line in _git(["diff", "--numstat", base, head], wt).stdout.splitlines():
        parts = (line.split("\t") + ["", ""])[:3]
        added, deleted, path = parts[0], parts[1], parts[2]
        n = (int(added) if added.isdigit() else 0) + (int(deleted) if deleted.isdigit() else 0)
        total += n
        if not is_artifact(path, arm):
            code += n
    return total, code


def score_checkout(wt: Path, task: dict, answer: str, arm: str) -> dict:
    base, head = doless.snapshot_commit(wt)
    new_files_all = doless.added_files(wt, base, head)
    lines_total, lines_code = numstat_totals(wt, base, head, arm)
    check = filter_check(doless.keel_check(wt, base, head, doless.DOLESS / task["card"], False), arm)
    surface = doless.surface_columns(check,
                                     [f for f in new_files_all if not is_artifact(f, arm)],
                                     task.get("expected", {}), False)
    regression = doless.run_regression(wt, task)
    oracle = doless.run_oracle(wt, task, answer)
    return {"diffHead": head, "changedLines": lines_total, "changedLinesCode": lines_code,
            "newFiles": new_files_all,
            "newFilesArtifacts": [f for f in new_files_all if is_artifact(f, arm)],
            "surface": surface,
            "regression": regression[0], "regressionTail": regression[2][-600:],
            "oracle": oracle[0], "oracleTail": oracle[2][-600:]}


def sum_usage(usages: list[dict]) -> dict:
    keys = ("sessions", "tokensInput", "tokensOutput", "tokensReasoning", "tokensCacheRead",
            "tokensCacheWrite")
    out = {}
    for k in keys:
        out[k] = sum(int(u.get(k, 0)) for u in usages)
    return out


def perform(task_id: str, arm: str, run_index: int, *, keep: bool = False) -> dict:
    task = doless.load_tasks()[task_id]
    task_text = (doless.DOLESS / task[doless.PROMPT_KEYS["explicit"]]).read_text(encoding="utf-8")
    title = f"tb-{task_id}-{arm}{run_index}-{uuid.uuid4().hex[:6]}"
    wt = runner.make_worktree(f"dl-{task_id}", arm, task["parentSha"])
    run_dir = driver.WORK / title
    run_dir.mkdir(parents=True, exist_ok=True)
    try:
        seed_worktree(wt, arm)
    except Exception as exc:
        raise RuntimeError(f"seed_worktree failed: {type(exc).__name__}: {exc}") from exc
    env = dict(runner.bench_env(task))
    env["OPENSPEC_TELEMETRY"] = "0"
    stages = build_stages(arm, wt, task_text)
    results, usages, prompts = [], [], []
    agent_error = None
    for name, prompt in stages:
        (run_dir / name).mkdir(parents=True, exist_ok=True)
        (run_dir / name / "prompt.txt").write_text(prompt, encoding="utf-8")
        prompts.append(prompt)
        log(f"[{title}] stage {name} start")
        t0 = time.monotonic()
        res = driver.run_agent(wt, prompt, f"{title}-{name}", env, run_dir / name)
        log(f"[{title}] stage {name} done wall={res['wall']}s rc={res['returnCode']} "
            f"timedOut={res['timedOut']} session={res.get('sessionID')}")
        results.append({"name": name, "sessionID": res.get("sessionID"),
                        "wallSeconds": res["wall"], "timedOut": res["timedOut"],
                        "returnCode": res["returnCode"], "stderrTail": res["stderrTail"][-200:]})
        usages.append(driver.subtree_tokens(res.get("sessionID")))
        (run_dir / name / "answer.txt").write_text("\n\n".join(res["texts"]), encoding="utf-8")
        if agent_error is None:
            if res.get("timedOut"):
                agent_error = f"agent_timeout:{name}"
            elif not res.get("sessionID"):
                agent_error = f"no_session_observed:{name}"
    if agent_error is None and not any(r["sessionID"] for r in results):
        agent_error = "no_session_observed"
    answer_parts = []
    for r in results:
        p = run_dir / r["name"] / "answer.txt"
        if p.is_file():
            answer_parts.append(p.read_text(encoding="utf-8"))
    answer = ("\n\n--- next stage ---\n\n").join(a for a in answer_parts if a.strip())
    usage = sum_usage(usages)
    row: dict = {}
    try:
        row = score_checkout(wt, task, answer, arm)
    except Exception as exc:
        row["evaluatorError"] = f"{type(exc).__name__}: {exc}"[:500]
    final_text = answer
    tokens_total = sum(usage.get(k, 0) for k in ("tokensInput", "tokensOutput", "tokensReasoning",
                                                  "tokensCacheRead", "tokensCacheWrite"))
    digests = {}
    for key, want in PINS.items():
        digests[key] = want
    for r in results:
        pp = run_dir / r["name"] / "prompt.txt"
        if pp.is_file():
            digests["prompt/" + arm + "-" + r["name"]] = runner.digest_bytes(pp.read_bytes())
    base_row = {
        "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "dolessVersion": doless.DOLESS_VERSION, "executor": "drael", "task": task_id,
        "split": task["split"], "category": task["category"], "arm": arm, "promptStyle": "explicit",
        "run": run_index, "requestedModel": driver.MODEL, "models": [driver.MODEL],
        "inferenceConfig": None, "effortObservation": "unobserved",
        "costProvenance": "unavailable",
        "opencodeCli": driver.opencode_version(),
        "methodology": {"s": "spec-kit-4-stage", "o": "openspec-2-stage"}[arm],
        "stages": results, "stageCount": len(results),
        "stageSessionIds": [r["sessionID"] for r in results],
        "artifactPrefixes": list(ARTIFACT_PREFIXES[arm]),
        "surfaceDigests": digests,
        "promptDigest": runner.digest_bytes(b"\n@@STAGE@@\n".join(p.encode("utf-8") for p in prompts)),
        "taskDigest": runner.digest_bytes(b"\0".join(
            (doless.DOLESS / task[k]).read_bytes() for k in (doless.PROMPT_KEYS["explicit"], "oracle", "card"))),
        "agentError": agent_error,
        "sessionId": next((r["sessionID"] for r in reversed(results) if r["sessionID"]), None),
        "costUsd": None, "costUsdEstimated": driver.estimate_usd(usage),
        "tokens": usage, "tokensTotal": tokens_total,
        "wallSeconds": round(sum(r["wallSeconds"] for r in results), 1),
        "transcript": str(run_dir),
        "answerTail": final_text[-400:],
    }
    base_row.update(row)
    if base_row.get("evaluatorError"):
        base_row["verdict"], base_row["verdictReasons"] = "INCOMPLETE", ["evaluator_error"]
    elif agent_error:
        base_row["verdict"], base_row["verdictReasons"] = "INCOMPLETE", [agent_error]
    else:
        base_row["verdict"], base_row["verdictReasons"] = doless.do_less_verdict(base_row)
    with doless.RESULTS.open("a", encoding="utf-8") as f:
        f.write(json.dumps(base_row, ensure_ascii=False) + "\n")
    log(json.dumps({k: base_row.get(k) for k in ("task", "arm", "run", "verdict", "verdictReasons",
                                                 "oracle", "regression", "changedLines",
                                                 "changedLinesCode", "tokensTotal",
                                                 "costUsdEstimated", "wallSeconds")},
                   ensure_ascii=False))
    if base_row["verdict"] != "PASS":
        log(f"oracleTail: {(base_row.get('oracleTail') or '')[-300:]}")
        log(f"regressionTail: {(base_row.get('regressionTail') or '')[-300:]}")
    driver.save_diff(wt, run_dir)
    if not (keep or base_row.get("evaluatorError")):
        doless.remove_checkout(wt)
    else:
        log(f"kept checkout: {wt}")
    return base_row


def openspec_version() -> str:
    p = subprocess.run(["openspec", "--version"], capture_output=True, text=True,
                       creationflags=NO_WINDOW, timeout=30, shell=True)
    return (p.stdout or p.stderr).strip().splitlines()[-1] if (p.stdout or p.stderr).strip() else f"exit {p.returncode}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--plan", type=Path)
    ap.add_argument("--task")
    ap.add_argument("--arm", choices=["s", "o"])
    ap.add_argument("-n", type=int, default=1)
    ap.add_argument("--keep", action="store_true")
    args = ap.parse_args()
    if not os.environ.get("TOKEN_BENCH_SCRATCH") or not os.environ.get("TOKEN_BENCH_GRAPHHELM_CLI"):
        raise SystemExit("TOKEN_BENCH_SCRATCH and TOKEN_BENCH_GRAPHHELM_CLI must be set")
    verify_pins()
    log(f"preflight: opencode={driver.opencode_version()} openspec={openspec_version()} "
        f"graphhelm_cli={os.environ.get('TOKEN_BENCH_GRAPHHELM_CLI')} "
        f"timeout_s={driver.TIMEOUT_S}")
    plan: list[tuple[str, str, int]] = []
    if args.smoke:
        plan = [("docs-config-risk", "s", 0), ("docs-config-risk", "o", 0)]
    elif args.plan:
        raw = json.loads(args.plan.read_text(encoding="utf-8"))
        plan = [(e["task"], e["arm"], e["run"]) for e in raw]
    elif args.task and args.arm:
        plan = [(args.task, args.arm, i) for i in range(1, args.n + 1)]
    else:
        raise SystemExit("give --smoke, --plan FILE, or --task T --arm A")
    for task_id, arm, index in plan:
        try:
            perform(task_id, arm, index, keep=args.keep)
        except Exception as exc:
            log(f"ENTRY FAILED {task_id} {arm} {index}: {type(exc).__name__}: {exc}")
            log(traceback.format_exc(limit=8))


if __name__ == "__main__":
    main()
