def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_pins() -> None:
    bad = []
    for key, want in PINS.items():
        if key.startswith("s/"):
            got = _sha(SK_DIR / key[2:])
        else:
            rel = key[2:]
            src = OS_INIT / (".opencode/commands/" if rel.endswith(".md") else "openspec/") / rel
            got = _sha(src)
        if got != want:
            bad.append((key, want, got))
    if bad:
        raise SystemExit("surface pin drift: " + json.dumps(bad))


def _git(args: list[str], wt: Path) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=wt, check=True, capture_output=True,
                          text=True, encoding="utf-8", errors="replace", creationflags=NO_WINDOW)


def seed_worktree(wt: Path, arm: str) -> None:
    if arm == "s":
        dest = wt / ".specify" / "templates"
        dest.mkdir(parents=True, exist_ok=True)
        for f in sorted((SK_DIR / "templates").iterdir()):
            if f.is_file():
                shutil.copy2(f, dest / f.name)
    else:
        shutil.copytree(OS_INIT / "openspec", wt / "openspec")


def available_docs(wt: Path) -> list[str]:
    """What the setup-tasks/setup-implement scripts would report as AVAILABLE_DOCS."""
    feat = wt / FEATURE_DIR
    if not feat.is_dir():
        return []
    out = []
    for p in sorted(feat.rglob("*")):
        rel = p.relative_to(feat).as_posix()
        out.append(rel if p.is_file() else rel.rstrip("/") if rel.endswith("/") else rel)
    return sorted(set(out))


def sk_body(stage_file: str, args_text: str) -> str:
    body = (SK_DIR / stage_file).read_text(encoding="utf-8")
    body = body.replace("$ARGUMENTS", args_text)
    body = body.replace("{SCRIPT}", "the setup script output given in the Stage Setup above")
    for ph, cmd in (("SPECIFY", "/speckit.specify"), ("PLAN", "/speckit.plan"),
                    ("TASKS", "/speckit.tasks"), ("IMPLEMENT", "/speckit.implement"),
                    ("CLARIFY", "/speckit.clarify"), ("CHECKLIST", "/speckit.checklist")):
        body = body.replace("__SPECKIT_COMMAND_" + ph + "__", cmd)
    return body


def os_body(cmd_file: str, args_text: str) -> str:
    return (OS_INIT / ".opencode" / "commands" / cmd_file).read_text(encoding="utf-8") \
        .replace("$ARGUMENTS", args_text)


