"""Cross-methodology do-less arms for the drael battery: arm s = Spec Kit (github/spec-kit) and
arm o = OpenSpec (Fission-AI/OpenSpec).

Same executor (drael/drael-v1 via `opencode run --auto`), same seven frozen tasks, same scorer
(doless.py functions), same per-session timeout as driver.py. Only the methodology surface
differs:

  s  four sequential fresh sessions in one checkout: specify -> plan -> tasks -> implement.
     Each prompt = deterministic prelude + the frozen spec-kit command template with $ARGUMENTS
     substituted. The .specify scripts do not exist in the checkout; their JSON outputs are given
     inline in the prelude (setup-plan/setup-tasks/check-prerequisites). The constitution stage is
     omitted (one-time project setup, not per-feature work); AGENTS.md substitutes for it.
  o  two sequential fresh sessions: opsx-propose -> opsx-apply, prompt = the real OpenSpec
     command markdown (generated by `openspec init --tools opencode`) with $ARGUMENTS
     substituted + minimal prelude. The openspec/ root is seeded from a pristine scaffold and the
     agent runs the real openspec CLI (v1.15.0) inside the checkout.

Documented adaptations (reported): headless execution (no interactive questions; assumptions are
recorded in artifacts); slash commands are delivered as expanded command text (how the harness
expands them anyway); methodology artifact directories are excluded from the do-less blocking
columns (unrequestedNewFiles and pathsOutsideCard) - s: specs/, .specify/; o: openspec/ - while
full diffs, changedLines, token and wall totals still include them.

Usage:
    python driver_cross.py --smoke                 # docs-config-risk through both arms, run 0
    python driver_cross.py --plan PLAN.json        # [{"task","arm","run"}, ...]
    python driver_cross.py --task T --arm s|o [-n N]

Environment (required): TOKEN_BENCH_SCRATCH, TOKEN_BENCH_GRAPHHELM_CLI.
Rows append to tools/token-bench/doless/results.jsonl, arm = "s"/"o".

Committed-copy notes: this file lives in tools/token-bench/; REPO resolves relative to the
file (override: TOKEN_BENCH_REPO) and OS_INIT defaults to tools/token-bench/doless/surfaces/
openspec-init (override: BENCH_OPENSPEC_INIT_DIR). Committed copy = as-run code plus the
ARTIFACT_PREFIXES fix noted below and a top-level `import traceback`; see the note at
ARTIFACT_PREFIXES.
"""
